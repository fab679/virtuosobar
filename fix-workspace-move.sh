#!/usr/bin/env bash
# Fix cross-monitor workspace moves (Super+Shift+Alt+Arrows).
#
# Upstream bug: after moving a workspace to another monitor, Omarchy focuses
# the stale pre-move id instead of the renumbered one, so focus jumps back
# to the monitor it just left. /usr/share is package-owned, so this installs
# a user shadow module (~/.config wins over stock on the Hyprland lua path)
# generated from your current stock file plus the fix.
#
# Re-run after every `omarchy update`; run with `uninstall` to drop the
# shadow and return to pure stock.
set -euo pipefail

SRC="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OMARCHY_PATH="${OMARCHY_PATH:-/usr/share/omarchy}"
STOCK="$OMARCHY_PATH/default/hypr/monitor-workspaces.lua"
SHADOW="$HOME/.config/default/hypr/monitor-workspaces.lua"

usage() {
  cat <<'EOF'
Usage:
  ./fix-workspace-move.sh           Install (or refresh) the fixed shadow module
  ./fix-workspace-move.sh status    Show whether the shadow is active
  ./fix-workspace-move.sh uninstall Remove the shadow, return to pure stock
EOF
}

cmd="${1:-install}"
case "$cmd" in
  install)
    [[ -f $STOCK ]] || { echo "error: stock file not found: $STOCK" >&2; exit 1; }
    command -v luac >/dev/null || echo "warning: luac not found, skipping syntax check" >&2
    mkdir -p "$(dirname "$SHADOW")"
    if [[ -f $SHADOW ]] && ! grep -q "VirtuosoBar shadow" "$SHADOW"; then
      bak="$SHADOW.bak.virtuoso.$(date +%s)"
      cp "$SHADOW" "$bak"
      echo "Backed up your existing shadow to: $bak"
    fi
    python3 "$SRC/lib/patch-workspace-move.py" "$STOCK" "$SHADOW"
    if command -v luac >/dev/null; then
      luac -p "$SHADOW" && echo "lua syntax OK: $SHADOW"
    fi
    echo ""
    echo "Done. Reload Hyprland to pick it up: hyprctl reload"
    echo "Move a workspace across monitors and focus should stay with it."
    ;;
  status)
    if [[ -f $SHADOW ]]; then
      if grep -q "VirtuosoBar shadow" "$SHADOW"; then
        head -5 "$SHADOW"
        echo "shadow ACTIVE (yours, generated by fix-workspace-move.sh)"
      else
        echo "shadow present but NOT ours: $SHADOW"
      fi
    else
      echo "no shadow: pure stock ($STOCK)"
    fi
    ;;
  uninstall)
    if [[ -f $SHADOW ]]; then
      if grep -q "VirtuosoBar shadow" "$SHADOW"; then
        rm "$SHADOW"
        echo "Removed shadow. Reload Hyprland: hyprctl reload"
      else
        echo "error: $SHADOW is not ours, refusing to delete" >&2
        exit 1
      fi
    else
      echo "no shadow installed"
    fi
    ;;
  *) usage; exit 1 ;;
esac
